package com.libredescarga.core.engine

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.runInterruptible
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.addJsonObject
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.put
import kotlinx.serialization.json.putJsonArray
import kotlinx.serialization.json.putJsonObject
import okhttp3.OkHttpClient
import okhttp3.RequestBody.Companion.toRequestBody
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.downloader.Downloader
import org.schabi.newpipe.extractor.downloader.Request
import org.schabi.newpipe.extractor.downloader.Response
import org.schabi.newpipe.extractor.exceptions.ReCaptchaException
import org.schabi.newpipe.extractor.localization.Localization
import org.schabi.newpipe.extractor.stream.AudioStream
import org.schabi.newpipe.extractor.stream.AudioTrackType
import org.schabi.newpipe.extractor.stream.DeliveryMethod
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.StreamType
import org.schabi.newpipe.extractor.stream.VideoStream
import java.util.Locale
import java.util.concurrent.TimeUnit
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Vía rápida para YouTube y YouTube Music con NewPipe Extractor: obtiene los formatos en Java, sin lanzar Python ni
 * resolver el JavaScript del reproductor con QuickJS (que en un teléfono de gama media tarda ~10 s).
 *
 * Devuelve el mismo JSON que `yt-dlp --dump-single-json`, así [InfoParser] arma las mismas calidades y tamaños, y los
 * identificadores de formato son los itags de YouTube, que yt-dlp entiende al descargar. Si algo falla, quien llama
 * usa yt-dlp como respaldo.
 */
@Singleton
class NewPipeYoutubeExtractor @Inject constructor() {

    @Volatile
    private var initialized = false

    /** [videoUrl] debe ser un enlace de video de YouTube (watch). Lanza una excepción si NewPipe no puede leerlo. */
    suspend fun fetchInfo(videoUrl: String): JsonObject = runInterruptible(Dispatchers.IO) {
        ensureInitialized()
        toYtDlpJson(StreamInfo.getInfo(ServiceList.YouTube, videoUrl))
    }

    private fun ensureInitialized() {
        if (initialized) return
        synchronized(this) {
            if (initialized) return
            NewPipe.init(OkHttpDownloader(), Localization.fromLocale(Locale.getDefault()))
            initialized = true
        }
    }

    private fun toYtDlpJson(info: StreamInfo): JsonObject = buildJsonObject {
        put("id", info.id)
        put("title", info.name)
        info.uploaderName?.let { put("uploader", it) }
        if (info.duration > 0) put("duration", info.duration)
        if (info.viewCount >= 0) put("view_count", info.viewCount)
        info.thumbnails.maxByOrNull { it.width }?.url?.let { put("thumbnail", it) }
        put("webpage_url", info.url)
        put("extractor", "youtube")
        put("extractor_key", "Youtube")
        if (info.streamType == StreamType.LIVE_STREAM || info.streamType == StreamType.AUDIO_LIVE_STREAM) {
            put("is_live", true)
        }

        putJsonArray("formats") {
            (info.videoOnlyStreams + info.videoStreams)
                .filter { it.isUsable() }
                .forEach { video -> addJsonObject { videoFormat(video) } }
            info.audioStreams
                .filter { it.isUsable() && (it.audioTrackType == null || it.audioTrackType == AudioTrackType.ORIGINAL) }
                .forEach { audio -> addJsonObject { audioFormat(audio) } }
        }

        // Subtítulos manuales por idioma; los automáticos se marcan "-orig", como en yt-dlp (y como los pide al descargar).
        val (automatic, manual) = info.subtitles.partition { it.isAutoGenerated }
        putJsonObject("subtitles") {
            manual.distinctBy { it.languageTag }.forEach { track ->
                putJsonArray(track.languageTag) { addJsonObject { put("name", track.displayLanguageName) } }
            }
        }
        putJsonObject("automatic_captions") {
            automatic.distinctBy { it.languageTag }.forEach { track ->
                putJsonArray("${track.languageTag}-orig") { addJsonObject { put("name", track.displayLanguageName) } }
            }
        }
    }

    private fun kotlinx.serialization.json.JsonObjectBuilder.videoFormat(video: VideoStream) {
        val ext = if (video.format == MediaFormat.WEBM) "webm" else "mp4"
        directDownload(video.content)
        put("format_id", video.itag.toString())
        put("ext", ext)
        put("vcodec", video.codec ?: if (ext == "webm") "vp9" else "avc1")
        put("acodec", if (video.isVideoOnly) "none" else "mp4a.40.2")
        put("height", video.height)
        if (video.fps > 0) put("fps", video.fps)
        if (video.bitrate > 0) put("tbr", video.bitrate / 1000.0)
        video.itagItem?.contentLength?.takeIf { it > 0 }?.let { put("filesize", it) }
        val label = "${video.resolution} ${video.quality}"
        put("dynamic_range", if ("HDR" in label.uppercase(Locale.ROOT)) "HDR" else "SDR")
    }

    private fun kotlinx.serialization.json.JsonObjectBuilder.audioFormat(audio: AudioStream) {
        val m4a = audio.format == MediaFormat.M4A
        val kbps = audio.averageBitrate.takeIf { it > 0 } ?: (audio.bitrate / 1000).takeIf { it > 0 }
        directDownload(audio.content)
        put("format_id", audio.itag.toString())
        put("ext", if (m4a) "m4a" else "webm")
        put("vcodec", "none")
        put("acodec", audio.codec ?: if (m4a) "mp4a.40.2" else "opus")
        kbps?.let {
            put("abr", it)
            put("tbr", it)
        }
        audio.itagItem?.contentLength?.takeIf { it > 0 }?.let { put("filesize", it) }
    }

    /**
     * Dirección directa del formato (ya descifrada por NewPipe) para que la descarga no tenga que volver a extraer el video:
     * yt-dlp la usa con --load-info-json. Se pide por trozos de 10 MB, igual que hace yt-dlp con YouTube (si no, YouTube
     * frena la descarga).
     */
    private fun kotlinx.serialization.json.JsonObjectBuilder.directDownload(url: String) {
        put("url", url)
        put("protocol", "https")
        putJsonObject("http_headers") { put("User-Agent", USER_AGENT) }
        putJsonObject("downloader_options") { put("http_chunk_size", HTTP_CHUNK_SIZE) }
    }

    /** Solo formatos que yt-dlp puede pedir por su itag (descarga HTTP directa) y en contenedores que la app maneja. */
    private fun VideoStream.isUsable(): Boolean =
        deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP && itag > 0 && height > 0 &&
            (format == MediaFormat.MPEG_4 || format == MediaFormat.WEBM)

    private fun AudioStream.isUsable(): Boolean =
        deliveryMethod == DeliveryMethod.PROGRESSIVE_HTTP && itag > 0

    private companion object {
        /** Mismo navegador con el que NewPipe obtuvo las direcciones (YouTube puede rechazar otro distinto). */
        const val USER_AGENT = "Mozilla/5.0 (Windows NT 10.0; Win64; x64; rv:140.0) Gecko/20100101 Firefox/140.0"
        const val HTTP_CHUNK_SIZE = 10_485_760L
    }

    /** Cliente HTTP que usa NewPipe para hablar con YouTube. */
    private class OkHttpDownloader : Downloader() {

        private val client = OkHttpClient.Builder()
            .connectTimeout(15, TimeUnit.SECONDS)
            .readTimeout(20, TimeUnit.SECONDS)
            .build()

        override fun execute(request: Request): Response {
            val body = request.dataToSend()?.toRequestBody()
            val builder = okhttp3.Request.Builder()
                .url(request.url())
                .method(request.httpMethod(), body)
                .header("User-Agent", USER_AGENT)
            request.headers().forEach { (name, values) ->
                builder.removeHeader(name)
                values.forEach { builder.addHeader(name, it) }
            }
            client.newCall(builder.build()).execute().use { response ->
                if (response.code == HTTP_TOO_MANY_REQUESTS) {
                    throw ReCaptchaException("YouTube pidió una verificación", request.url())
                }
                return Response(
                    response.code,
                    response.message,
                    response.headers.toMultimap(),
                    response.body.string(),
                    response.request.url.toString(),
                )
            }
        }

        private companion object {
            const val HTTP_TOO_MANY_REQUESTS = 429
        }
    }
}
